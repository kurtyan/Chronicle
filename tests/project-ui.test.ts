    const firstCard = () => overview.getByTestId('milestone-card').filter({ has: overview.getByRole('heading', { name: first.name, exact: true }) })
    const secondCard = () => overview.getByTestId('milestone-card').filter({ has: overview.getByRole('heading', { name: second.name, exact: true }) })
    await expect(firstCard().getByText('2.0 小时', { exact: true })).toBeVisible()
    await expect(secondCard().getByText('0 分钟', { exact: true })).toBeVisible()
    const body = page.locator('.ProseMirror[contenteditable="true"]')
    const draftText = unique('尚未提交的个人感悟')
    await body.fill(draftText)
    await expect.poll(() => saveStarted).toBe(true)

    await editor.getByRole('button', { name: '编辑 / 状态', exact: true }).click()
    const renamed = unique('跨窗口重命名')
    await editor.getByRole('dialog').getByLabel('名称', { exact: true }).fill(renamed)
    await editor.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
    await expect(editor.getByRole('heading', { name: renamed, exact: true })).toBeVisible()
    await expect(page.getByTestId('project-relations').getByRole('button', { name: `${area.name} › ${renamed}`, exact: true })).toBeVisible()
    await expect(overview.getByRole('heading', { name: renamed, exact: true })).toBeVisible()
    await expect(body).toContainText(draftText)
    expect((await (await request.get(`/api/notes/${note.id}`)).json()).contentHtml).toBe(note.contentHtml)

    await editor.goto('/')
    await editor.locator(`[data-task-id="${task.id}"]`).click()
    await editor.getByRole('button', { name: '调整归属', exact: true }).click()
    const assignment = editor.getByRole('dialog')
    await assignment.getByRole('button', { name: '选择主里程碑', exact: true }).click()
    await assignment.getByTestId('entity-reference-options').getByText(second.name, { exact: true }).click()
