test('stage completion, handwritten Note review and later edits preserve the confirmed history', async ({ page, request }) => {
  test.setTimeout(75_000)
  const area = await (await request.post('/api/areas', { data: { name: unique('复盘方向') } })).json()
  const milestone = await (await request.post('/api/milestones', { data: { areaId: area.id, name: unique('人工验收里程碑'), goal: '验证结果并保留经验', completionCriteria: '已经核对实际成果' } })).json()
  await page.goto(`/projects/milestones/${milestone.id}`)
  await page.getByRole('button', { name: '编辑 / 状态', exact: true }).click()
  const edit = page.getByRole('dialog')
  await edit.getByRole('combobox', { name: '状态', exact: true }).selectOption('completed')
  await edit.getByRole('checkbox', { name: '我已核对成果，确认里程碑完成。复盘可以稍后补充。', exact: true }).check()
  await edit.getByRole('button', { name: '确认完成并保存', exact: true }).click()
  await expect(page.getByText('当前已完成，待复盘。', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: '新建完成复盘', exact: true }).click()
  await expect(page).toHaveURL(/\/notes\?id=/)
  const noteId = new URL(page.url()).searchParams.get('id')!
  const firstText = unique('第一次确认的实践经验')
  await page.locator('.ProseMirror[contenteditable="true"]').fill(firstText)
  await expect.poll(async () => (await (await request.get(`/api/notes/${noteId}`)).json()).contentHtml).toContain(firstText)
  const review = (await (await request.get(`/api/project-reviews?targetType=milestone&targetId=${milestone.id}`)).json())[0]
  expect(review.status).toBe('draft')
  expect((await (await request.get(`/api/milestones/${milestone.id}`)).json()).reviewStatus).toBe('pending')
  await page.getByTestId('project-relations').getByRole('button', { name: `${area.name} › ${milestone.name}`, exact: true }).click()
  await page.getByRole('button', { name: '核对 / 版本', exact: true }).click()
  const reviewDialog = page.getByRole('dialog')
  await expect(reviewDialog).toContainText(firstText)
  await reviewDialog.getByRole('button', { name: '确认当前 Note 为复盘版本', exact: true }).click()
  await expect(reviewDialog.locator('summary').filter({ hasText: /^版本 1/ })).toBeVisible()
  await reviewDialog.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByText('完成复盘 · 已确认', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '编辑 Note', exact: true }).click()
  const laterText = unique('后来形成的新认识')
  await page.locator('.ProseMirror[contenteditable="true"]').fill(laterText)
  await expect.poll(async () => (await (await request.get(`/api/notes/${noteId}`)).json()).contentHtml).toContain(laterText)
  await page.getByTestId('project-relations').getByRole('button', { name: `${area.name} › ${milestone.name}`, exact: true }).click()
  await expect(page.getByText('Note 在确认后有新修改', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: '核对 / 版本', exact: true }).click()
  const versions = page.getByRole('dialog')
  await expect(versions).toContainText(laterText)
  const firstVersion = versions.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^版本 1/ }) }).first()
  await expect(firstVersion).toContainText(firstText)
  await expect(firstVersion).not.toContainText(laterText)
  const saved = await (await request.get(`/api/project-reviews/${review.id}`)).json()
  expect(saved.versions).toHaveLength(1)
  expect(saved.versions[0].contentHtml).toContain(firstText)
  expect(saved.noteChangedSinceConfirmation).toBe(true)
})

test('a failed LLM draft can be retried with a larger independent output budget', async ({ page, request }) => {
  test.setTimeout(60_000)
  const originalSettings = await (await request.get('/api/settings/llm')).json()
  const area = await (await request.post('/api/areas', { data: { name: unique('预算方向') } })).json()
  const milestone = await (await request.post('/api/milestones', { data: { areaId: area.id, name: unique('输出预算里程碑') } })).json()
  let retryId: string | undefined
  try {
    // A deliberately unavailable local provider gives a deterministic failure without spending tokens.
    const configured = await request.put('/api/settings/llm', { data: { baseUrl: 'http://127.0.0.1:1/v1', model: 'project-ui-unavailable-provider', apiKey: '', timeoutMs: 1000 } })
    expect(configured.ok(), await configured.text()).toBe(true)
    await page.goto(`/projects/milestones/${milestone.id}`)
    const budget = page.getByRole('combobox', { name: '输出与推理预算', exact: true })
    await expect(budget).toHaveValue('4000')
    await budget.selectOption('8000')
    const createdResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/project-insights' && response.request().method() === 'POST')
    await page.getByRole('button', { name: '生成 LLM 回顾草稿', exact: true }).click()
    const response = await createdResponse
    expect(response.ok()).toBe(true)
    expect(response.request().postDataJSON().budget.maxOutputTokens).toBe(8000)
    const originalDraft = await response.json()
    await expect.poll(async () => (await (await request.get(`/api/project-insights/${originalDraft.id}`)).json()).status).toBe('error')
    await expect(page.getByText('生成失败', { exact: false })).toBeVisible()
    await budget.selectOption('16000')
    const retriedResponse = page.waitForResponse(result => new URL(result.url()).pathname === `/api/project-insights/${originalDraft.id}/retry` && result.request().method() === 'POST')
    await page.getByRole('button', { name: '重新生成', exact: true }).click()
    const retried = await retriedResponse
    expect(retried.ok()).toBe(true)
    expect(retried.request().postDataJSON().budget.maxOutputTokens).toBe(16000)
    const draft = await retried.json()
    retryId = draft.id
    expect(draft.budget.maxOutputTokens).toBe(16000)
    expect(draft.previousDraftId).toBe(originalDraft.id)
    const previous = await (await request.get(`/api/project-insights/${originalDraft.id}`)).json()
    expect(previous.status).toBe('error')
    expect(previous.budget.maxOutputTokens).toBe(8000)
  } finally {
    if (retryId) await request.post(`/api/project-insights/${retryId}/cancel`)
    await request.put('/api/settings/llm', { data: originalSettings })
  }
})
